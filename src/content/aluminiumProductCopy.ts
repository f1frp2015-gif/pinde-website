function localiseSpecValue(value: string) {
  return russianSpecValues[value] ?? value;
}

export function getLocalizedAluminiumProduct(product: Product, locale: AluminiumProductLocale): Product {
  if (locale === "en") return product;

  const copy = russianCopy[product.slug];
  if (!copy) throw new Error(`Missing Russian product copy for ${product.slug}`);

  return {
    ...product,
    ...copy,
    specs: product.specs.map((spec) => ({
      label: russianSpecLabels[spec.label] ?? spec.label,
      value: localiseSpecValue(spec.value),
    })),
  };
}

